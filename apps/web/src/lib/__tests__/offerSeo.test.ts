import { describe, expect, it } from "vitest";

import { offerPlace, offerSeoDescription, offerSeoTitle } from "../offerSeo";

describe("где проходит вакансия — из адреса", () => {
    it.each([
        ["Россия, Иркутская область, Иркутск", "Иркутская область"],
        ["Ольхонский район, Иркутская область, Россия, Шара-Тоготское", "Иркутская область"],
        ["Россия, Республика Татарстан, Апастово", "Республика Татарстан"],
        ["Россия, Ямало-Ненецкий автономный округ, Салехард", "Ямало-Ненецкий автономный округ"],
        ["Россия, Алтайский край, Колывань", "Алтайский край"],
        ["Россия, Москва", "Москва"],
        ["Россия, Санкт-Петербург, Средний проспект В.О., 74", "Санкт-Петербург"],
        ["село Передовое, Орлиновский муниципальный округ, Балаклавский район, Севастополь, Россия, Водопадная улица", "Севастополь"],
        ["Россия, бухта Средняя", "Россия"],
        ["Россия", "Россия"],
        ["Peru, Cusco, Cusco", "Peru"],
        ["Гана, Большая Аккра, Аккра", "Гана"],
        ["Kenya, Nairobi County, Nairobi", "Kenya"],
        ["Поповка", "Поповка"],
    ])("%s → %s", (address, place) => {
        expect(offerPlace(address)).toBe(place);
    });

    it("пустой адрес — без места", () => {
        expect(offerPlace("")).toBeNull();
        expect(offerPlace(null)).toBeNull();
    });
});

describe("заголовок для поиска", () => {
    it("название организатора + регион; «волонтёрство» не повторяем", () => {
        expect(offerSeoTitle({ title: "Волонтёрство с видом на Байкал", address: "Ольхонский район, Иркутская область, Россия", highlights: [] }, "ru"))
            .toBe("Волонтёрство с видом на Байкал, Иркутская область | Гудсёрфинг");
    });

    it("без слова «волонтёрство» в названии — добавляем", () => {
        expect(offerSeoTitle({ title: "Работа в хостеле", address: "Россия, Москва", highlights: [] }, "ru"))
            .toBe("Работа в хостеле — волонтёрство, Москва | Гудсёрфинг");
        expect(offerSeoTitle({ title: "Farm help", address: "Peru, Cusco", highlights: [] }, "en"))
            .toBe("Farm help — volunteering, Peru | GoodSurfing");
    });

    it("длинное название: сначала без «волонтёрства», потом без места, совсем длинное — обрезаем по слову, не длиннее 70 символов", () => {
        const long = "Археологическая экспедиция на Таманском полуострове";
        const title = offerSeoTitle({ title: long, address: "Россия, Краснодарский край, Темрюк", highlights: [] }, "ru");
        expect(title).toBe(`${long} | Гудсёрфинг`);
        const huge = "Очень длинное название вакансии, которое само по себе длиннее семидесяти символов";
        const short = offerSeoTitle({ title: huge, address: null, highlights: [] }, "ru");
        expect(short).toBe("Очень длинное название вакансии, которое само по себе… | Гудсёрфинг");
        expect(short.length).toBeLessThanOrEqual(70);
    });
});

describe("описание для поиска", () => {
    it("направление, место, условия и начало текста организатора — до 160 символов", () => {
        const text = offerSeoDescription({
            title: "Волонтёрство с видом на Байкал",
            address: "Ольхонский район, Иркутская область, Россия",
            category: "Работа в хостеле",
            highlights: ["Койко-место", "Полный пансион", "от 14 дн."],
            shortDescription: "Байкал — чудо, с которым надо обязательно встретиться. Мы готовы показать его вам и научить работать в гостевом доме.",
        });
        expect(text.startsWith("Работа в хостеле. Иркутская область. Койко-место, Полный пансион, от 14 дн. Байкал")).toBe(true);
        expect(text.length).toBeLessThanOrEqual(160);
    });

    it("направление «Другое» не пишем", () => {
        expect(offerSeoDescription({ title: "x", category: "Другое", address: "Россия, Москва", highlights: [], shortDescription: "Текст" })).toBe("Москва. Текст");
    });

    it("без данных — только текст организатора", () => {
        expect(offerSeoDescription({ title: "x", highlights: [], shortDescription: "Помощь на ферме" })).toBe("Помощь на ферме");
    });
});
