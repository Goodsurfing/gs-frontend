/** id в виде UUID — так бэкенд хранит организации, пользователей, курсы и уроки */
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * Похож ли адрес на настоящий id. Нет — страница сразу «не найдено» (404) без запроса к API:
 * бэкенд на такие id отвечает 400, а у курсов и уроков — ещё и текстом ошибки SQL.
 */
export function isUuid(id: string): boolean {
    return UUID.test(id);
}
