export interface TopicLanding {
    slug: string;
    kind: "topic" | "region";
    /** Короткое название для ссылок и хаба */
    name: string;
    query: { categoryIds?: number[]; search?: string };
    title: string;
    h1: string;
    description: string;
    intro: string[];
    faq: Faq[];
}

