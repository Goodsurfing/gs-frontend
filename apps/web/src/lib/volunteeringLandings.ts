/** Тексты на en/es — по общему шаблону с названием направления */
export function genericLanding(name: string, t: (key: string) => string): { title: string; h1: string; description: string; intro: string[]; faq: Faq[] } {
    const fill = (key: string) => t(key).replace("{name}", name);
    return {
        title: fill("landing.title"),
        h1: fill("landing.h1"),
        description: fill("landing.description"),
        intro: [fill("landing.intro1"), fill("landing.intro2")],
        faq: [{ q: t("landing.faqCostQ"), a: t("landing.faqCostA") }, { q: t("landing.faqExpQ"), a: t("landing.faqExpA") }],
    };
}
