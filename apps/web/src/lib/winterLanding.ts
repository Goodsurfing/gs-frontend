import type { Faq } from "./volunteeringLandings";

export interface WinterSeason {
    /** Окно для фильтра overlapStart/overlapEnd, Y-m-d */
    start: string;
    end: string;
    /** «2026/27» */
    label: string;
}

const pad = (n: number) => String(n).padStart(2, "0");
const isLeap = (year: number) => (year % 4 === 0 && year % 100 !== 0) || year % 400 === 0;

/**
 * Ближайшая зима (1 декабря – конец февраля) для даты today (Y-m-d по Москве): с марта по декабрь —
 * зима, которая начинается в декабре этого года; в январе и феврале — текущая.
 */
export function winterSeason(today: string): WinterSeason {
    const [year = 2026, month = 1] = today.split("-").map(Number);
    const startYear = month <= 2 ? year - 1 : year;
    const endYear = startYear + 1;
    return {
        start: `${startYear}-12-01`,
        end: `${endYear}-02-${pad(isLeap(endYear) ? 29 : 28)}`,
        label: `${startYear}/${String(endYear).slice(2)}`,
    };
}

